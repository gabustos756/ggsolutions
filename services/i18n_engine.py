def get_i18n_context(lang="es", rubro="general", nombre_negocio=""):
    """
    Retorna el diccionario de palabras i18n y la tupla traducida de (headline, subheadline)
    según el idioma seleccionado. Fallback en Español ('es').
    """
    lang_code = str(lang or "es").lower().strip()
    if lang_code not in I18N_DICTIONARY:
        lang_code = "es"

    dic = I18N_DICTIONARY[lang_code]

    headline_tr = None
    subheadline_tr = None

    if lang_code != "es" and rubro in HERO_TRANSLATIONS and lang_code in HERO_TRANSLATIONS[rubro]:
        h_tpl, s_tpl = HERO_TRANSLATIONS[rubro][lang_code]
        headline_tr = h_tpl.format(nombre=nombre_negocio)
        subheadline_tr = s_tpl.format(nombre=nombre_negocio)

    return {
        "lang": lang_code,
        "i18n": dic,
        "headline_tr": headline_tr,
        "subheadline_tr": subheadline_tr
    }


def translate_pilares(pilares_list, lang="es", rubro="general"):
    """
    Traduce la lista de pilares visuales si el idioma != 'es'.
    """
    lang_code = str(lang or "es").lower().strip()
    if lang_code == "es" or rubro not in PILARES_TRANSLATIONS or lang_code not in PILARES_TRANSLATIONS[rubro]:
        return pilares_list

    tr_list = PILARES_TRANSLATIONS[rubro][lang_code]
    translated = []
    for idx, pilar in enumerate(pilares_list):
        p_copy = dict(pilar)
        if idx < len(tr_list):
            p_copy["title"] = tr_list[idx]["title"]
            p_copy["desc"] = tr_list[idx]["desc"]
            p_copy["tag"] = tr_list[idx]["tag"]
        translated.append(p_copy)
    return translated
